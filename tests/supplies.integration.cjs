const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const base = process.env.AZURE_TEST_API || 'http://127.0.0.1:5173';
if (new URL(base).hostname !== '127.0.0.1' || new URL(base).protocol !== 'http:') throw new Error('Supply tests require the loopback test database.');
const origin = 'http://127.0.0.1:4173';
async function phone() {
  const response = await fetch(base + '/api/session', { headers: { Origin: origin } });
  assert.equal(response.status, 200);
  const { token } = await response.json();
  return async (path, body) => {
    const result = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { Origin: origin, Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: result.status, ...await result.json() };
  };
}
(async () => {
  const [a, b] = await Promise.all([phone(), phone()]);
  assert.equal((await fetch(base + '/api/supplies')).status, 401);
  assert.equal((await fetch(base + '/api/supplies', { headers: { Origin: 'https://unrelated.example' } })).status, 403);
  const id = randomUUID(), name = 'Local QA filters ' + id;
  const fields = { name, quantity: '2 packs', priority: 'out', notes: 'Confirm machine model' };
  let result = await a('/api/supplies', { id, fields });
  assert.equal(result.status, 201); assert.equal(result.item.revision, 1);
  assert.equal((await a('/api/supplies', { id, fields: { name: 'Must not overwrite' } })).item.name, name);
  const second = (await b('/api/supplies')).items.find(x => x.id === id);
  assert.equal(second.quantity, '2 packs'); assert.equal(second.priority, 'out');
  const dup = await b('/api/supplies', { id: randomUUID(), fields: { name: '  ' + name.toUpperCase().replaceAll(' ', '  ') + '  ' } });
  assert.equal(dup.status, 409); assert.equal(dup.item.id, id);
  const path = '/api/supplies/' + id;
  result = await a(path, { revision: 1, changes: { status: 'ordered', notes: 'Delivery tomorrow' } });
  assert.equal(result.status, 200);
  assert.equal((await b(path, { revision: 1, changes: { status: 'restocked' } })).status, 409);
  const reportId = randomUUID(), reportBody = { id: reportId, date: '2099-11-02', notes: '', supplies: [] };
  const report = await a('/api/report', reportBody);
  assert.equal(report.status, 201); assert(report.supplyRequests.some(x => x.id === id && x.status === 'ordered'));
  assert(report.summary.includes(name + ' · 2 packs [Ordered]'));
  result = await b(path, { revision: 2, changes: { status: 'restocked' } });
  const at = result.item.restockedAt; assert(at > 0);
  result = await a(path, { revision: 3, changes: { notes: 'Put in kitchen cupboard' } });
  assert.equal(result.item.restockedAt, at);
  const oldReport = await a('/api/report?id=' + reportId);
  assert.equal(oldReport.supplyRequests.find(x => x.id === id).status, 'ordered');
  assert.equal((await a('/api/report', reportBody)).summary, report.summary);
  const newReport = await a('/api/report', { ...reportBody, id: randomUUID() });
  assert(!newReport.supplyRequests.some(x => x.id === id));
  const nextId = randomUUID();
  result = await b('/api/supplies', { id: nextId, fields });
  assert.equal(result.status, 201, 'restocked items may be requested again');
  assert.equal((await a(path, { revision: 4, changes: { status: 'needed' } })).status, 409, 'reopening cannot create a duplicate active item');
  result = await b('/api/supplies/' + nextId, { revision: 1, changes: { status: 'cancelled' } });
  assert.equal(result.status, 200);
  result = await a(path, { revision: 4, changes: { status: 'needed' } });
  assert.equal(result.status, 200); assert.equal(result.item.restockedAt, null);
  for (const changes of [{ name: ' ' }, { status: 'purchased' }, { priority: 'bad' }, { notes: 'x'.repeat(3001) }, { id: 'overwrite' }]) assert.equal((await a(path, { revision: 5, changes })).status, 400);
  const raceName = 'Concurrent local item ' + randomUUID();
  const race = await Promise.all([a('/api/supplies', { id: randomUUID(), fields: { name: raceName } }), b('/api/supplies', { id: randomUUID(), fields: { name: raceName } })]);
  assert.deepEqual(race.map(x => x.status).sort(), [201, 409]);
  const concurrent = await Promise.all([a(path, { revision: 5, changes: { quantity: '3 packs' } }), b(path, { revision: 5, changes: { quantity: '4 packs' } })]);
  assert.deepEqual(concurrent.map(x => x.status).sort(), [200, 409]);
  console.log('PASS: shared supply requests, duplicate and concurrent-edit protection, quantities, status/history, cancellation, validation and immutable report snapshots.');
})().catch(error => { console.error(error); process.exitCode = 1; });
